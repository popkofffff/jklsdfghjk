package com.hunter.ozonjob.data.api

/**
 * ЕДИНСТВЕННОЕ место, где описана связь с Ozon Job.
 *
 * У Ozon Job нет публичного API, поэтому реальные пути снимаются с трафика
 * официального приложения "Озон Работа" (ru.ozon.hire) через HttpCanary или Charles:
 *
 *  1. Ставишь HttpCanary, включаешь перехват.
 *  2. Открываешь Ozon Job: вход по номеру телефона -> смотришь запрос отправки SMS
 *     и запрос проверки кода (в ответе будет токен).
 *  3. Вкладка смен: выбираешь день и длительность -> смотришь запрос списка слотов.
 *  4. Жмешь "Забронировать" -> смотришь запрос брони.
 *  5. Подставляешь Host, пути и JSON-поля ниже. Если схема тела запроса
 *     отличается, поправь только модели в этом же пакете.
 *
 * Код всего остального приложения от этой конфигурации не зависит.
 */
object ApiConfig {

    /** Базовый хост API (заменить после снятия трафика). */
    const val HOST: String = "https://api-job.ozon.ru"

    /** User-Agent официального приложения, если сервер его проверяет. */
    const val USER_AGENT: String = "OzonJob/1.0 (Android)"

    // ------------------ Авторизация ------------------

    /** Отправка SMS-кода на номер телефона. */
    const val PATH_SEND_CODE: String = "/auth/send-code"

    /** Проверка кода -> в ответе токен */
    const val PATH_VERIFY_CODE: String = "/auth/verify"

    // ------------------ Смены ------------------

    /** Список доступных слотов смен. Получает дату и длительность. */
    const val PATH_SLOTS: String = "/shifts/slots"

    /** Бронирование слота по его id. */
    const val PATH_BOOK: String = "/shifts/book"

    // ------------------ Параметры охоты ------------------

    /** Первый запрос уходит за это время до 06:00, чтобы "разогреть" сессию. */
    const val PRE_ARM_MS: Long = 8_000

    /** Интервал опроса слотов в горячей фазе. */
    const val POLL_INTERVAL_MS: Long = 300

    /** Сколько длится горячая фаза, прежде чем охота снимается. */
    const val HUNT_WINDOW_MS: Long = 180_000

    /** Повторные попытки брони, если сервер вернул ошибку. */
    const val BOOK_RETRIES: Int = 8
    const val BOOK_RETRY_DELAY_MS: Long = 120
}
